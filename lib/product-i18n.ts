export function getProductText(locale: ProductLocale, key: MessageKey, values?: Record<string, string | number>) {
  let text = catalogs[locale][key] ?? en[key] ?? key
  for (const [name, value] of Object.entries(values ?? {})) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

export function translateProductPhrase(locale: ProductLocale, source: string, values?: Record<string, string | number>) {
  const phraseMap = { ...meetingPhrases[locale], ...workToolPhrases[locale], ...activityPhrases[locale] }
  const group = /^Group (\d+)$/.exec(source)
  let text = group
    ? (phraseMap['Group {number}'] ?? source).replace('{number}', group[1])
    : phraseMap[source] ?? source
  for (const [name, value] of Object.entries(values ?? {})) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

export function getToolText(locale: ProductLocale, id: string, field: 'name' | 'description') {
  const key = `tool.${id}.${field}` as MessageKey
  return getProductText(locale, key)
}

